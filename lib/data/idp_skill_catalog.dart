class IdpSkillCategory {
  static const leadership = 'leadership';
  static const comm = 'comm';
  static const team = 'team';
  static const analytic = 'analytic';
  static const digital = 'digital';
  static const self = 'self';
  static const innovation = 'innovation';
  static const customer = 'customer';
  static const finance = 'finance';
  static const change = 'change';
  static const ei = 'ei';
  static const project = 'project';

  static const all = [leadership, comm, team, analytic, digital, self, innovation, customer, finance, change, ei, project];

  static String label(String id) {
    switch (id) {
      case leadership:
        return 'Liderlik va boshqaruv';
      case comm:
        return 'Muloqot va kommunikatsiya';
      case team:
        return 'Jamoada ishlash';
      case analytic:
        return 'Strategik va analitik fikrlash';
      case digital:
        return 'Raqamli va texnik kompetensiyalar';
      case self:
        return 'Shaxsiy samaradorlik';
      case innovation:
        return 'Innovatsiya va ijodkorlik';
      case customer:
        return 'Mijozga yo\'naltirilganlik';
      case finance:
        return 'Moliyaviy savodxonlik';
      case change:
        return 'O\'zgarish va moslashuvchanlik';
      case ei:
        return 'Hissiy intellekt';
      case project:
        return 'Loyihalarni boshqarish';
      default:
        return id;
    }
  }
}

